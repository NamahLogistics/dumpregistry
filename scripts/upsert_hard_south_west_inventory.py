def main() -> None:
    hard_rows: list[dict] = []
    rejected_soft = rejected_nongov = 0
    for row in FACILITIES:
        row = dict(row)
        # normalize materials if stored as group names
        am = row["accepted_materials"]
        if am and am[0] in ("HHW", "E_WASTE", "BULKY", "APPLIANCE", "TIRES"):
            row["accepted_materials"] = mats(*am)
        else:
            row["accepted_materials"] = mats(am)
        if not is_gov_url(row.get("source_url", "")):
            rejected_nongov += 1
            continue
        if not is_hard_facility(row):
            rejected_soft += 1
            continue
        hard_rows.append(row)

    facilities = json.loads(FAC_PATH.read_text())
    by_key = {(f.get("city_slug"), f.get("name")): i for i, f in enumerate(facilities)}
    added = updated = 0
    for row in hard_rows:
        key = (row["city_slug"], row["name"])
        if key in by_key:
            facilities[by_key[key]] = {**facilities[by_key[key]], **row}
            updated += 1
        else:
            facilities.append(row)
            by_key[key] = len(facilities) - 1
            added += 1

    FAC_PATH.write_text(json.dumps(facilities, indent=2) + "\n")

    target = set(TARGET_CITIES)
    hard_total = sum(1 for f in facilities if f.get("city_slug") in target and is_hard_facility(f))
    per_city = {c: sum(1 for f in facilities if f.get("city_slug") == c and is_hard_facility(f)) for c in sorted(target)}
    print(
        json.dumps(
            {
                "script_rows": len(FACILITIES),
                "hard_upserted": len(hard_rows),
                "rejected_soft": rejected_soft,
                "rejected_nongov": rejected_nongov,
                "added": added,
                "updated": updated,
                "metro_hard_total": hard_total,
                "per_city": per_city,
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()

