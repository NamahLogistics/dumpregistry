def mats(*groups):
    out, seen = [], set()
    for g in groups:
        if isinstance(g, str):
            g = [g]
        for m in g:
            if m not in ITEMS:
                raise SystemExit(f"unknown slug {m}")
            if m not in seen:
                seen.add(m)
                out.append(m)
    return out


def is_gov_url(url: str) -> bool:
    if not url:
        return False
    u = url.lower()
    return ".gov" in u or ".us/" in u or "gov.com/" in u or u.rstrip("/").endswith((".us", "gov.com"))


