def main() -> None:
    upserts = []
    for name, builder in CITIES.items():
        rows = builder()
        slugs = [r["item_slug"] for r in rows]
        if sorted(slugs) != sorted(ITEMS):
            raise SystemExit(f"{name}: expected {ITEMS}, got {slugs}")
        for r in rows:
            if r["reviewed_by"] != REVIEWER or r["last_verified_at"] != VERIFIED:
                raise SystemExit(f"{name}/{r['item_slug']}: bad review metadata")
            if r["needs_review"] is not False or r["zip"] is not None:
                raise SystemExit(f"{name}/{r['item_slug']}: zip/needs_review invalid")
            if len(r["steps"]) != 3 or not (1 <= len(r["faqs"]) <= 2):
                raise SystemExit(f"{name}/{r['item_slug']}: steps/faqs count")
        upserts.extend(rows)

    rules = json.loads(RULES_PATH.read_text())
    index = {(r.get("city_slug"), r["item_slug"]): i for i, r in enumerate(rules) if r.get("city_slug")}
    added = updated = 0
    for row in upserts:
        key = (row["city_slug"], row["item_slug"])
        if key in index:
            rules[index[key]] = row
            updated += 1
        else:
            index[key] = len(rules)
            rules.append(row)
            added += 1

    for r in rules:
        if r.get("common_disposal_fee"):
            r["common_disposal_fee"] = str(r["common_disposal_fee"])[:80]
        if r.get("nearest_facility_type"):
            r["nearest_facility_type"] = str(r["nearest_facility_type"])[:120]

    RULES_PATH.write_text(json.dumps(rules, indent=2) + "\n")

    print(f"cities: {len(CITIES)}")
    print(f"rules upserted: {added + updated} (added={added}, updated={updated})")
    print(f"total rules now: {len(rules)}")
    print("sample source_urls:")
    for u in [
        "https://www.clevelandohio.gov/city-hall/departments/public-works/divisions/waste/waste",
        "https://dpw.dc.gov/service/household-hazardous-waste-hhw-e-cycling-document-shredding",
        "https://ocrra.org/waste/household-toxics/",
    ]:
        print(f"  {u}")


if __name__ == "__main__":
    main()
